import React from 'react'

interface ReportTemplateProps {
  title: string
  data: any[]
  columns: { key: string; header: string }[]
}

const ReportTemplate: React.FC<ReportTemplateProps> = ({ 
  title, 
  data, 
  columns 
}) => {
  return (
    <div className="report-template p-6 font-mono text-sm bg-white text-black">
      <div className="text-center border-b pb-4 mb-4">
        <h2 className="text-lg font-bold">CAFÉ ANALÍTICA C.A.</h2>
        <h3 className="text-base">{title}</h3>
        <p className="text-xs">Fecha: {new Date().toLocaleString()}</p>
      </div>

      <table className="w-full border-collapse">
        <thead>
          <tr className="bg-gray-200">
            {columns.map((col, index) => (
              <th key={index} className="border p-2 text-left">{col.header}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {data.map((row, rowIndex) => (
            <tr key={rowIndex}>
              {columns.map((col, colIndex) => (
                <td key={colIndex} className="border p-2">
                  {row[col.key] || ''}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>

      <div className="mt-4 text-center text-xs">
        <p>Reporte generated by POS Nativo Beta</p>
      </div>
    </div>
  )
}

export default ReportTemplate